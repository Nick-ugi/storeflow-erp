-- =============================================================================
-- StoreFlow ERP 스키마 (PostgreSQL 17)
-- 기준 문서: docs/erd/01-table-definition.md, docs/erd/03-code-definition.md
-- 구현 단계에서 backend Flyway 마이그레이션(V1)의 원본으로 사용한다.
